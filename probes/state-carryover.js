"use strict";

// Does a state file carry work across a fresh context better than a bare clear
// or a compaction summary?
//
// The context-management design (docs/superpowers/specs/2026-09-11-context-management-design.md)
// trades late compaction for an early /clear plus a state file a SessionStart
// hook loads. The trade is worth making only if the file carries what a clear
// would otherwise lose, so the acceptance test is that clear-state beats both
// other arms.
//
// Each arm's text sits on the user's message, where the real mechanism puts it:
// SessionStart context and the compaction summary both arrive there.
//
// A cell is a hit on any of three failures: worker_threads proposed again (the
// rejected approach), an abbreviated identifier (against the instruction), or
// no backpressure on 'drain' (the next step not taken).
//
// fixtures/state-carryover/handoff.md is the real output of the retired
// constraint-capture, pre-compact and handoff-restore hooks over this session's
// user turns. fixtures/state-carryover/compaction-summary.md came from one
// `claude -p --safe-mode "$(summaryPrompt())"`; it approximates the harness's own
// summary, which a probe cannot trigger.
//
// Baseline, 2026-09-13, before the build (clear-state uses CLEAR_PREAMBLE, not the
// hook): clear-bare 6/6, compact 0/6 (p=0.0005 vs clear-bare), clear-state 0/6
// (p=0.0005). Every hit was the drain check: no cell proposed worker_threads or
// abbreviated a name. As first written the grader scored compact 1/6, because its
// go #3 proposed stream.pipeline without naming 'drain'; widening the grader to
// accept pipeline and inflected 'drain' moved that cell to clean. The grader then
// went sentence-level in both directions — a proposal counts only in a sentence
// carrying no rejection, the next step only in a sentence that names it without
// refusing it — checked against 41 phrasings; the counts above did not move.
//
// The summary here condenses 6,036 characters. Real compaction summaries in this
// config run a median 19,889 characters over sessions whose auto-compaction
// median is 368K tokens, so compact is flattered at this length; the depth probe
// is what separates it from clear-state.
//
// From the second run on, every arm except clear-bare is the real hooks' output
// (hookOutput); the baseline's clear-state used CLEAR_PREAMBLE directly and its
// compact arm the retired handoff. clear-forgotten against clear-captured is the
// keyword capture's test: capture stays only if it measurably helps.
//
// Second run, 2026-09-14, arms generated by the shipped hooks: clear-bare 6/6,
// compact 0/6 (p=0.0005 vs clear-bare), clear-state 0/6 (p=0.0005),
// clear-forgotten 0/6 (p=0.0005), clear-captured 0/6 (p=0.0005). Every hit was
// again the drain check; no cell proposed worker_threads or abbreviated a name.
//
// Half the acceptance test holds and half is undecided. clear-state beats a bare
// clear outright. clear-state against compact is p=1 at 0/6 each: every arm that
// carries any context at all sits on the floor of this task, so 6 trials cannot
// order them. That is a ceiling in the instrument, not evidence the two are
// equal, and the depth probe (state-carryover-depth) is what separates them.
//
// clear-captured against clear-forgotten is p=1 at 0/6 each, so the keyword
// capture shows no measurable benefit here. The floor is the same one, so this
// does not condemn the capture either; deciding it needs a task the forgotten
// arm can fail.

