// The exact text the hooks inject, from a throwaway repository, so the arms
// measure what ships rather than a copy of it.
function inScratchRepository(stateText, body) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "carryover-repo-"));
  const configDir = fs.mkdtempSync(path.join(os.tmpdir(), "carryover-config-"));
  try {
    spawnSync("git", ["init", "-q", "."], { cwd: root });
    fs.mkdirSync(path.join(root, ".claude"));
    fs.writeFileSync(path.join(root, ".claude", "state.md"), stateText);
    return body(root, { ...process.env, CLAUDE_CONFIG_DIR: configDir });
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
    fs.rmSync(configDir, { recursive: true, force: true });
  }
}

function hookOutput(source, stateText) {
  return inScratchRepository(stateText, (root, env) => {
    const reply = spawnSync(
      process.execPath,
      [path.join(HOOKS, "state-restore.js")],
      {
        input: JSON.stringify({ source, cwd: root }),
        encoding: "utf8",
        env,
      },
    );
    return JSON.parse(reply.stdout).hookSpecificOutput.additionalContext;
  });
}

// Instructions Claude never recorded: the case keyword capture exists for.
const FORGOTTEN_STATE_FILE = STATE_FILE.replace(
  /## Instructions\n\n[\s\S]*?\n\n## Unconfirmed/,
  "## Instructions\n\n## Unconfirmed",
);

function capturedStateFile() {
  return inScratchRepository(FORGOTTEN_STATE_FILE, (root, env) => {
    for (const prompt of userTurns()) {
      spawnSync(process.execPath, [path.join(HOOKS, "constraint-capture.js")], {
        input: JSON.stringify({ session_id: "carryover", prompt, cwd: root }),
        encoding: "utf8",
        env,
      });
    }
    return fs.readFileSync(path.join(root, ".claude", "state.md"), "utf8");
  });
}

const REJECTED_IMPORT =
  /require\(\s*["'](?:node:)?worker_threads["']\s*\)|from\s+["'](?:node:)?worker_threads["']|new\s+Worker\s*\(/;
const PROPOSAL_VERB =
  /\b(?:use|using|try|trying|reintroduce|reintroducing|switch(?:ing)?\s+to)\s+`?(?:node:)?worker_threads/i;
// Naming the rejected approach in order to rule it out is the memory working,
// so a sentence counts as a re-proposal only when it carries no rejection. A
// lookbehind on the verb cannot do this: "decided not to use worker_threads"
// puts the negation two tokens away, and "could use ... but that breaks the
// memory rule" puts it in the next clause.
// Each cue has to be a rejection on its own. A bare "no", "rules" or "stay"
// excused a real proposal that happened to share the sentence with one.
const REJECTION_CUE =
  /\b(?:not|never|avoid(?:ed|ing)?|without|instead|rather than|reject(?:ed|s)?|revert(?:ed)?|dropped|breaks?|broke|bad idea|cannot|can't|won't|single-threaded)\b|n't|\brule[ds]?\b[^.]{0,15}\bout\b|\bno\s+(?:\w+\s+)?(?:use|using|try|trying|switch\w*|reintroduc\w+)\b/i;

// Backpressure by hand waits for 'drain'; stream.pipeline applies the same
// backpressure itself, measured at 2 chunks of lead against 199 for a loop that
// ignores what write() returns. A bare "stream pipeline" is the design the
// session already had, so only a call or the promises import counts.
const NEXT_STEP_MENTION =
  /\bdrain(s|ed|ing)?\b|\bbackpressure\b|\bpipeline\s*\(|node:stream\/promises/i;

// Naming the mechanism and then declining it is not doing it, so the step counts
// only where one sentence names it without refusing it in the same breath.
// Proximity to the word backpressure was too narrow: the refusal usually sits in
// the clause after the mention ("resuming on drain, but I'll just write in a
// loop"). Residual gap: a refusal in one sentence and a bare restatement in the
// next ("we ignore backpressure; it drains eventually") still reads as taken.
const NEXT_STEP_REFUSED =
  /\b(?:skip\w*|without|instead of|rather than|no need|not need\w*|unnecessary|not necessary|ignor\w+|small enough|fast enough)\b|\bno\s+backpressure\b|n't\s+(?:necessary|needed|need|bother)/i;

function sentencesOf(text) {
  return text.split(/(?<=[.!?;:])\s+|\n+/);
}

function proposesRejectedApproach(output) {
  if (REJECTED_IMPORT.test(output)) return true;
  return sentencesOf(output).some(
    (sentence) => PROPOSAL_VERB.test(sentence) && !REJECTION_CUE.test(sentence),
  );
}

function takesNextStep(output) {
  return sentencesOf(output).some(
    (sentence) =>
      NEXT_STEP_MENTION.test(sentence) && !NEXT_STEP_REFUSED.test(sentence),
  );
}

function grade(output, fixtureText = "") {
  const violations = [];
  if (proposesRejectedApproach(output))
    violations.push("proposed worker_threads again");
  const abbreviated = naming.grade(output, fixtureText).violations;
  if (abbreviated.length > 0)
    violations.push(`abbreviated: ${abbreviated.join(", ")}`);
  if (!takesNextStep(output))
    violations.push("next step not taken (backpressure on drain)");
  return { violations };
}

function userTurns() {
  return KEY_TURNS.filter((turn) => turn.startsWith("User: ")).map((turn) =>
    turn.slice("User: ".length),
  );
}

function summaryPrompt() {
  return (
    "Summarize this conversation so the work can continue in a new context " +
    "window. Cover the user's requests, decisions, files touched, errors and " +
    "fixes, and the current work and next step.\n\n<conversation>\n" +
    SESSION_TRANSCRIPT +
    "\n</conversation>"
  );
}

